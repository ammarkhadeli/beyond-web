import {chromium} from '@playwright/test';
const browser=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERROR',m.text().slice(0,300));});
await page.addInitScript(()=>localStorage.setItem('beyond-v2-settings',JSON.stringify({quality:'high',voice:false,sound:false,sensitivity:1,beginnerPauses:false})));
await page.route('**/api/health',r=>r.fulfill({contentType:'application/json',body:'{"aiConfigured":false}'}));
page.on('response',r=>{if(r.status()>=400)console.log('HTTP',r.status(),r.url());});
await page.goto('http://127.0.0.1:5174');
await page.waitForTimeout(2500);
console.log('INITIAL BODY', (await page.locator('body').innerText()).slice(0,2000));
await page.screenshot({path:'.local/v2-initial.png'});
await page.getByRole('button',{name:'Start flight',exact:true}).waitFor({state:'visible',timeout:90000});
await page.waitForTimeout(3500);
await page.screenshot({path:'.local/v2-setup.png'});
await page.getByLabel('Difficulty').selectOption('commander');
await page.getByRole('button',{name:'Start flight',exact:true}).click();
await page.waitForTimeout(2000);
await page.screenshot({path:'.local/v2-pad-cockpit.png'});console.log('PAD COCKPIT CAPTURED');
await page.mouse.move(720,450);await page.mouse.move(1090,450,{steps:8});await page.waitForTimeout(500);
await page.screenshot({path:'.local/v2-pad-look.png'});
await page.keyboard.press('v');await page.keyboard.press('c');await page.waitForTimeout(1000);
await page.screenshot({path:'.local/v2-pad-external.png'});console.log('PAD EXTERNAL CAPTURED');
await page.keyboard.press('Escape');await page.getByRole('button',{name:'End flight',exact:true}).click();
await page.getByRole('button',{name:'Moon',exact:true}).click();await page.getByLabel('Start location').selectOption('approach');
await page.getByRole('button',{name:'Start flight',exact:true}).click();await page.waitForTimeout(1500);
await page.screenshot({path:'.local/v2-moon-cockpit.png'});
await page.keyboard.press('c');await page.waitForTimeout(500);await page.screenshot({path:'.local/v2-moon-external.png'});
await browser.close();console.log('Review screenshots complete');
